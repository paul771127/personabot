def find_simplified(text: str) -> list[str]:
    """回傳出現過的簡體字,依出現順序,不重複。沒有就回空清單。"""
    seen: set[str] = set()
    out: list[str] = []
    for ch in text:
        if ch in SIMPLIFIED_ONLY and ch not in seen:
            seen.add(ch)
            out.append(ch)
    return out
